CREATE TABLE account_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    current_balance NUMERIC(19, 4) NOT NULL,
    reserved_balance NUMERIC(19, 4) NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_account_balances_account
        FOREIGN KEY (account_id) REFERENCES accounts(id),
    CONSTRAINT uq_account_balances_account UNIQUE (account_id),
    CONSTRAINT chk_account_balances_current_non_negative
        CHECK (current_balance >= 0),
    CONSTRAINT chk_account_balances_reserved_non_negative
        CHECK (reserved_balance >= 0),
    CONSTRAINT chk_account_balances_reserved_not_exceed_current
        CHECK (reserved_balance <= current_balance)
);

