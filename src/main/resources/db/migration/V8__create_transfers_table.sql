CREATE SEQUENCE transfer_reference_seq
    START WITH 100001
    INCREMENT BY 1;

CREATE TABLE transfers (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           public_id UUID NOT NULL UNIQUE,
                           reference_number VARCHAR(40) NOT NULL UNIQUE,

                           owner_user_id BIGINT NOT NULL,
                           source_account_id BIGINT NOT NULL,
                           beneficiary_id BIGINT NOT NULL,
                           destination_account_id BIGINT,

                           beneficiary_name VARCHAR(201) NOT NULL,
                           destination_iban VARCHAR(34) NOT NULL,
                           destination_bank_name VARCHAR(150) NOT NULL,

                           amount NUMERIC(19, 4) NOT NULL,
                           currency VARCHAR(3) NOT NULL,

                           type VARCHAR(20) NOT NULL,
                           status VARCHAR(20) NOT NULL,
                           failure_reason VARCHAR(50),

                           created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           completed_at TIMESTAMP WITH TIME ZONE,

                           CONSTRAINT fk_transfers_owner
                               FOREIGN KEY (owner_user_id)
                                   REFERENCES users(id),

                           CONSTRAINT fk_transfers_source_account
                               FOREIGN KEY (source_account_id)
                                   REFERENCES accounts(id),

                           CONSTRAINT fk_transfers_beneficiary
                               FOREIGN KEY (beneficiary_id)
                                   REFERENCES beneficiaries(id),

                           CONSTRAINT fk_transfers_destination_account
                               FOREIGN KEY (destination_account_id)
                                   REFERENCES accounts(id),

                           CONSTRAINT chk_transfers_amount_positive
                               CHECK (amount > 0),

                           CONSTRAINT chk_transfers_failure_state
                               CHECK (
                                       (status = 'FAILED' AND failure_reason IS NOT NULL)
                                       OR
                                       (status <> 'FAILED' AND failure_reason IS NULL)
                                   ),

                           CONSTRAINT chk_transfers_destination_by_type
                               CHECK (
                                       (type = 'INTERNAL' AND destination_account_id IS NOT NULL)
                                       OR
                                       (type = 'EXTERNAL' AND destination_account_id IS NULL)
                                   ),

                           CONSTRAINT chk_transfers_completed_at
                               CHECK (
                                       (status = 'COMPLETED' AND completed_at IS NOT NULL)
                                       OR
                                       (status <> 'COMPLETED' AND completed_at IS NULL)
                                   )
);