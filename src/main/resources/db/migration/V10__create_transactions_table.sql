CREATE SEQUENCE transaction_reference_seq
    START WITH 100001
    INCREMENT BY 1;

CREATE TABLE transactions (
                              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                              public_id UUID NOT NULL UNIQUE,
                              reference_number VARCHAR(40) NOT NULL UNIQUE,

                              account_id BIGINT NOT NULL,
                              transfer_id BIGINT,

                              type VARCHAR(50) NOT NULL,
                              direction VARCHAR(20) NOT NULL,

                              amount NUMERIC(19, 4) NOT NULL,
                              currency VARCHAR(3) NOT NULL,

                              created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT fk_transactions_account
                                  FOREIGN KEY (account_id)
                                      REFERENCES accounts(id),

                              CONSTRAINT fk_transactions_transfer
                                  FOREIGN KEY (transfer_id)
                                      REFERENCES transfers(id),

                              CONSTRAINT chk_transactions_amount_positive
                                  CHECK (amount > 0),

                              CONSTRAINT uq_transactions_business_movement
                                  UNIQUE (transfer_id, account_id, type, direction)
);
